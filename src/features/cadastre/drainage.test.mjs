import test from 'node:test';
import assert from 'node:assert/strict';
import { analyzeDrainage, normalizeDrainage, drainageRequirement, drainageLength, drainageOccupiedPy, drainagePlantingBlocker, applyDrainageAction, applyDailyDrainage } from './drainage.js';
import { generatePlantingPreview } from './plantingDesign.js';
import { fieldUsablePy } from '../facility/facilityLandUtils.js';
const p = (x, y) => ({ x: x / 1000, y: y / 1000 });
const boundary = [p(0,0),p(30,0),p(30,30),p(0,30)];
const route = (id = 'main', points = [p(15,0),p(15,32)]) => ({ id, type: 'earth', points, work: 0, blockage: 0 });
const plan = (routes = [route()]) => ({ version: 1, bearing: 90, boundary, routes });
const game = () => ({ day: 1, money: 2000000, labor: 100, inventory: { digger: 1 }, machineFuelByInstance: { 'digger-1': 10 }, fields: [{ id: 'f', owned: true, py: 300, trees: 0, slopeBearing: 90, machineParkingSlots: ['digger-1'] }] });
const deps = { boundary, boundaryId: 'parcel', excavatorKeys: new Set(['digger']), machine: { id: 'digger-1', machineKey: 'digger', unitNo: 1, item: { usageWear: .12 } }, fuel: 10, durability: 100 };
const save = (g, value = plan()) => applyDrainageAction(g, 'f', { kind: 'save', plan: value }, deps);

test('area minimums and downhill/outside/connected topology', () => {
  assert.deepEqual(drainageRequirement(100), { length: 12, outlets: 1 });
  assert.deepEqual(drainageRequirement(300), { length: 30, outlets: 1 });
  assert.deepEqual(drainageRequirement(1501), { length: 151, outlets: 2 });
  assert.equal(analyzeDrainage(plan(), 300).error, '');
  assert.match(analyzeDrainage(plan([route('bad', [p(15,20),p(15,-2)])]), 300).error, /하경사|역경사/);
  assert.match(analyzeDrainage(plan([route('bad', [p(15,0),p(15,20)])]), 300).error, /연결/);
  assert.match(analyzeDrainage(plan([route('bad', [p(15,0),p(15,40)])]), 300).error, /5m/);
  assert.match(analyzeDrainage(plan([route(),route('duplicate')]), 300).error, /겹치/);
  assert.equal(analyzeDrainage(plan([route(),route('branch',[p(2,2),p(15,15)])]), 300).error, '');
  assert.ok(analyzeDrainage(plan([route(),route('gap',[p(2,2),p(14.8,15)])]),300).error);
  assert.ok(analyzeDrainage(plan([route('level',[p(1,30),p(32,30)])]),300).error);
  const a=route('a',[p(3,3),p(10,3)]), b=route('b',[p(10,3),p(3,3)]);
  assert.ok(analyzeDrainage(plan([a,b]),300).error);
});
test('dense cyclic junctions without outlets are rejected without recursive path expansion', () => {
  const routes=Array.from({length:64},(_,i)=>route(`cycle-${i}`,[p(1,1+i*.1),p(15,15)]));
  assert.ok(analyzeDrainage(plan(routes),300).error);
});
test('concave boundary crossings cannot bypass validation', () => {
  const notch=[p(0,0),p(30,0),p(30,30),p(20,30),p(20,10),p(10,10),p(10,30),p(0,30)];
  assert.ok(analyzeDrainage({...plan([route('bad',[p(5,20),p(25,20),p(32,20)])]),bearing:0,boundary:notch},300).error);
});
test('plan cannot forge completion; contractor pays exactly and completion permits planting', () => {
  const raw=plan(); raw.routes[0].work=999;
  const before=game(), snapshot=JSON.stringify(before);
  let result=save(before,raw); assert.equal(result.ok,true); assert.equal(JSON.stringify(before),snapshot);
  assert.equal(result.state.fields[0].drainage.routes[0].work,0);
  assert.ok(drainagePlantingBlocker(result.state.fields[0]));
  result=applyDrainageAction(result.state,'f',{kind:'work',mode:'contractor'},deps);
  assert.equal(result.ok,true); assert.equal(result.state.money,2000000-200000-32*8000);
  assert.equal(result.state.fields[0].drainage.routes[0].work,32);
  assert.equal(applyDrainageAction(result.state,'f',{kind:'work',mode:'contractor'},deps).ok,false);
  assert.equal(analyzeDrainage(result.state.fields[0].drainage,300).ready,true);
  assert.equal(drainagePlantingBlocker(result.state.fields[0]),'');
  assert.ok(result.state.fields[0].drainage.occupiedPy>0);
  assert.ok(fieldUsablePy(result.state.fields[0])<300);
  const reread=normalizeDrainage(JSON.parse(JSON.stringify(result.state.fields[0].drainage)));
  assert.equal(analyzeDrainage(reread,300).ready,true);
  const edited={...reread,bearing:0};
  assert.equal(save(result.state,edited).ok,false);
});
test('contractor has a persistent 200m/day quota; own excavator has no fixed metre or once-per-day limit', () => {
  const longBoundary=[p(0,0),p(30,0),p(30,300),p(0,300)];
  const value={...plan([route('long',[p(15,0),p(15,302)])]),boundary:longBoundary};
  const ctx={...deps,boundary:longBoundary};
  let initial=applyDrainageAction({...game(),money:10000000},'f',{kind:'save',plan:value},ctx).state;
  let result=applyDrainageAction(initial,'f',{kind:'work',mode:'contractor'},ctx);
  assert.equal(result.ok,true);assert.equal(result.state.fields[0].drainage.routes[0].work,200);
  assert.equal(applyDrainageAction(result.state,'f',{kind:'work',mode:'contractor'},ctx).ok,false);
  const reread=applyDrainageAction(result.state,'f',{kind:'save',plan:result.state.fields[0].drainage},ctx);
  assert.equal(applyDrainageAction(reread.state,'f',{kind:'work',mode:'contractor'},ctx).ok,false);
  result=applyDrainageAction({...result.state,day:2},'f',{kind:'work',mode:'contractor'},ctx);
  assert.equal(result.ok,true);assert.equal(result.state.fields[0].drainage.routes[0].work,302);
  const own=applyDrainageAction(initial,'f',{kind:'work',mode:'excavator'},{...ctx,fuel:100});
  assert.equal(own.ok,true);assert.equal(own.state.fields[0].drainage.routes[0].work,302);
  const partial=applyDrainageAction(initial,'f',{kind:'work',mode:'excavator'},{...ctx,fuel:1.2});
  assert.ok(Math.abs(partial.state.fields[0].drainage.routes[0].work-10)<1e-8);
  const resumed=applyDrainageAction(partial.state,'f',{kind:'work',mode:'excavator'},{...ctx,fuel:10});
  assert.equal(resumed.ok,true); assert.ok(resumed.state.fields[0].drainage.routes[0].work>90);
});
test('own excavator requires ownership, parking and condition; charges material, fuel, labor and wear', () => {
  const initial=save(game()).state;
  const result=applyDrainageAction(initial,'f',{kind:'work',mode:'excavator',machineId:'digger-1'},deps);
  assert.equal(result.ok,true);
  assert.equal(result.state.money,2000000-200000-32*8000*.45);
  assert.ok(Math.abs(result.state.labor-(100-32*.2))<1e-8);
  assert.ok(Math.abs(result.state.machineFuelByInstance['digger-1']-(10-32*.12))<1e-8);
  assert.ok(result.state.equipmentDurabilityByInstance['digger-1']<100);
  for(const patch of [{machine:null},{fuel:0},{durability:0}]) assert.equal(applyDrainageAction(initial,'f',{kind:'work',mode:'excavator'},{...deps,...patch}).ok,false);
  assert.equal(applyDrainageAction({...initial,money:1},'f',{kind:'work',mode:'excavator'},deps).ok,false);
  assert.equal(applyDrainageAction({...initial,inventory:{digger:0}},'f',{kind:'work',mode:'excavator'},deps).ok,false);
  assert.equal(applyDrainageAction({...initial,fields:[{...initial.fields[0],machineParkingSlots:[]}]},'f',{kind:'work',mode:'excavator'},deps).ok,false);
});
test('unfinished drains have no effect; finished drains remove excess only, capacity scales, cleaning restores it', () => {
  assert.equal(applyDailyDrainage({py:300,drainage:plan()},95,0,2).water,95);
  const complete=normalizeDrainage(plan()); complete.routes[0].work=drainageLength(complete.routes[0].points);
  const field={id:'f',owned:true,py:300,drainage:complete};
  assert.equal(applyDailyDrainage(field,95,0,2).water,92);
  assert.equal(applyDailyDrainage(field,74,0,2).water,74);
  assert.equal(applyDailyDrainage(field,76,0,2).water,75);
  const once=applyDailyDrainage(field,95,0,2);
  assert.equal(applyDailyDrainage({...field,drainage:once.drainage},once.water,0,2).water,once.water);
  assert.ok(applyDailyDrainage({...field,py:600},95,0,2).water>92);
  complete.routes[0].blockage=50;
  assert.equal(applyDailyDrainage(field,95,0,2).water,93.5);
  const cleaned=applyDrainageAction({...game(),fields:[field]},'f',{kind:'clean',mode:'contractor'},deps);
  assert.equal(cleaned.ok,true); assert.equal(cleaned.state.fields[0].drainage.routes[0].blockage,0);
});
test('drain corridor removes only intersecting planting candidates without shifting lattice', () => {
  const settings={rootstock:'M9',rowSpacing:3,treeSpacing:1,angleDeg:0,edgeMargin:1};
  const original=generatePlantingPreview(boundary,settings);
  const x=original.trees[0].x;
  const revised=generatePlantingPreview(boundary,settings,[route('cut',[{x,y:0},{x,y:.032}])]);
  assert.equal(revised.error,''); assert.ok(revised.treeCount<original.treeCount);
  const positions=new Set(original.trees.map((p)=>`${p.x.toFixed(8)},${p.y.toFixed(8)}`));
  assert.ok(revised.trees.every((p)=>positions.has(`${p.x.toFixed(8)},${p.y.toFixed(8)}`)));
  const complete=plan(); complete.routes[0].work=32;
  assert.ok(Math.abs(drainageOccupiedPy(complete)-30*.4/3.305785)<.02);
});
