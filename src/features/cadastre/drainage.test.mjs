  const g=game(); g.fields[0].trees=20;
  assert.equal(drainagePlantingBlocker(g.fields[0]),'');
  const s=save(g); assert.equal(s.ok,true);
  assert.equal(applyDrainageAction(s.state,'f',{kind:'work',mode:'contractor'},deps).ok,false);
