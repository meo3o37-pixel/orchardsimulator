import { finalizeCropDailyFieldState, finalizeNonCropDailyFieldState } from '../quality/dailyFieldUpdateUtils';

export const finalizeAdvanceDayField = (params, deps) => {
  const {
    field,
    nextDay,
    month,
    weatherName,
    nextNutrition,
    nextWater,
    nextWeed,
    nextCanopySunlight,
    canopySunlightQualityBonus,
    weedVigorPenaltyNoCrop,
    nextTankWater,
    nextTankUnits,
    nextGroundwaterTonsBase,
    nextFacilityDurabilityByKey,
    nextRepairMap,
    nextTankDurabilityByFacility,
    evSlowChargedKwh,
    nextEvSlowChargeReservedInstanceId,
    nextPlan,
    microSprinklerEnabled,
    microSprinklerRan,
    fieldSurfaceResult,
    fieldBiologyResult
  } = params;

  const {
    herbicideDailyVigorPenalty,
    nextHerbicideEffectState,
    weedGrowthReductionUntilDay
  } = fieldSurfaceResult;
  const {
    nextTaskLastDoneDayByKey,
    nextTaskProgress,
    nextSprayUsageLitersByPesticide,
    nextBloomInsecticidePenaltyState,
    nextFoliarVigorBoost,
    pestVigorPenalty,
    nextPruningBranchWasteKg,
    nextLeafWasteKg,
    nextDroppedFruitWasteKg,
    vigorAgeMul,
    bloomDailyQualityPenalty,
    fieldWithNextFruitLoad,
    nextFruitLoadPerTree,
    nextFruitLoadReductionByAge,
    coldQualityPenalty,
    appliedBaseDailyVigorDelta,
    appliedFruitLoadVigorDelta,
    nextColdDamageFruitLoadLossTotal,
    nextColdDamagePending,
    appliedFoliarVigorBoostToday,
    coldVigorPenalty,
    weedVigorPenalty,
    nextWinterTreeStress,
    nextWinterDamageLevel,
    nextWinterDeathRisk,
    winterDamageLogText,
    winterTreeStressVigorPenalty,
    pestProfileResult
  } = fieldBiologyResult;

  const {
    currentPestProfile,
    currentDiseaseProfile,
    nextPestProfile,
    nextDiseaseProfile,
    nextOverwinterPestProfile,
    nextOverwinterDiseaseProfile,
    nextPest,
    nextPestOutbreakState,
    nextSlowDecayState,
    nextPruningEffect,
    nextElectricPruningPestBoost,
    pruningEffect,
    pruningEffectActive,
    pestOutbreakQualityPenalty
  } = pestProfileResult;

  if (!field.cropId) {
    return {
      kind: 'non-crop',
      nextField: finalizeNonCropDailyFieldState({
        field,
        nextDay,
        nextWater,
        nextCanopySunlight,
        nextWeed,
        herbicideDailyVigorPenalty,
        weedVigorPenaltyNoCrop,
        nextNutrition,
        currentPestProfile,
        currentDiseaseProfile,
        nextOverwinterPestProfile,
        nextOverwinterDiseaseProfile,
        nextTankWater,
        nextTankUnits,
        nextGroundwaterTonsBase,
        nextFacilityDurabilityByKey,
        nextRepairMap,
        nextTankDurabilityByFacility,
        evSlowChargedKwh,
        nextEvSlowChargeReservedInstanceId,
        nextPlan,
        weedGrowthReductionUntilDay,
        microSprinklerEnabled,
        microSprinklerRan,
        nextTaskLastDoneDayByKey,
        nextTaskProgress,
        nextSprayUsageLitersByPesticide,
        nextBloomInsecticidePenaltyState,
        nextHerbicideEffectState,
        nextFoliarVigorBoost
      }, {
        clamp: deps.clamp,
        composePestGaugeValue: deps.composePestGaugeValue,
        tankUnitWaterMapFromUnits: deps.tankUnitWaterMapFromUnits,
        normalizePestProfile: deps.normalizePestProfile,
        normalizeDiseaseProfile: deps.normalizeDiseaseProfile
      }),
      deadAdd: 0,
      hailLogText: '',
      winterDamageLogText
    };
  }

  const cropDailyFieldResult = finalizeCropDailyFieldState({
    field,
    nextDay,
    month,
    weatherName,
    nextNutrition,
    nextWater,
    nextWeed,
    nextPest,
    nextTaskProgress,
    vigorAgeMul,
    pruningEffectActive,
    pruningEffect,
    fieldWithNextFruitLoad,
    nextCanopySunlight,
    canopySunlightQualityBonus,
    nextPruningBranchWasteKg,
    nextLeafWasteKg,
    nextDroppedFruitWasteKg,
    nextTankWater,
    nextTankUnits,
    nextGroundwaterTonsBase,
    nextFacilityDurabilityByKey,
    nextRepairMap,
    nextTankDurabilityByFacility,
    evSlowChargedKwh,
    nextEvSlowChargeReservedInstanceId,
    nextPlan,
    nextFruitLoadPerTree,
    nextFruitLoadReductionByAge,
    nextColdDamageFruitLoadLossTotal,
    nextColdDamagePending,
    nextPruningEffect,
    nextElectricPruningPestBoost,
    nextFoliarVigorBoost,
    nextPestProfile,
    nextDiseaseProfile,
    nextOverwinterPestProfile,
    nextOverwinterDiseaseProfile,
    nextSlowDecayState,
    nextPestOutbreakState,
    nextBloomInsecticidePenaltyState,
    nextHerbicideEffectState,
    appliedBaseDailyVigorDelta,
    appliedFruitLoadVigorDelta,
    appliedFoliarVigorBoostToday,
    herbicideDailyVigorPenalty,
    pestVigorPenalty,
    weedVigorPenalty,
    nextWinterTreeStress,
    nextWinterDamageLevel,
    nextWinterDeathRisk,
    winterTreeStressVigorPenalty,
    coldVigorPenaltyApplied: coldVigorPenalty,
    bloomDailyQualityPenalty,
    pestOutbreakQualityPenalty,
    coldQualityPenalty,
    weedGrowthReductionUntilDay,
    microSprinklerEnabled,
    microSprinklerRan,
    nextTaskLastDoneDayByKey,
    nextSprayUsageLitersByPesticide
  }, {
    clamp: deps.clamp,
    crops: deps.crops,
    canopyTrainingTaskKey: deps.canopyTrainingTaskKey,
    thinningQualityRecoveryBonusMax: deps.thinningQualityRecoveryBonusMax,
    leafPluckingDailyQualityRecoveryAtFullProgress: deps.leafPluckingDailyQualityRecoveryAtFullProgress,
    canopyTrainingDailyQualityBonusEarlyDone: deps.canopyTrainingDailyQualityBonusEarlyDone,
    canopyTrainingDailyQualityBonusLateDone: deps.canopyTrainingDailyQualityBonusLateDone,
    hailQualityPenaltyByWeather: deps.hailQualityPenaltyByWeather,
    calendarGrowthPercent: deps.calendarGrowthPercent,
    dailyQualityPenaltyFromNutrition: deps.dailyQualityPenaltyFromNutrition,
    dailyPestQualityPenalty: deps.dailyPestQualityPenalty,
    fruitDiseaseQualityPenaltyBreakdown: deps.fruitDiseaseQualityPenaltyBreakdown,
    fruitDiseaseCompositeQualityPressure: deps.fruitDiseaseCompositeQualityPressure,
    dailyWaterQualityPenalty: deps.dailyWaterQualityPenalty,
    dailyHighVigorQualityPenalty: deps.dailyHighVigorQualityPenalty,
    dailyFruitOverloadQualityPenaltyForField: deps.dailyFruitOverloadQualityPenaltyForField,
    dailyFruitLoadOptimalQualityBonusForField: deps.dailyFruitLoadOptimalQualityBonusForField,
    ageTargetTaskProgressStatusOfField: deps.ageTargetTaskProgressStatusOfField,
    cropRowsByVarietyAndAge: deps.cropRowsByVarietyAndAge,
    fieldFacilityCountOf: deps.fieldFacilityCountOf,
    dailyPestDeathChance: deps.dailyPestDeathChance,
    dailyPestDeathCount: deps.dailyPestDeathCount,
    dailyNaturalDeathCount: deps.dailyNaturalDeathCount,
    tankUnitWaterMapFromUnits: deps.tankUnitWaterMapFromUnits,
    monthTaskText: deps.monthTaskText,
    toDate: deps.toDate
  });

  return {
    kind: 'crop',
    winterDamageLogText,
    ...cropDailyFieldResult
  };
};
